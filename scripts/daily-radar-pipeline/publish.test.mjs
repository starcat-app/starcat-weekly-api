/**
 * 发布适配器离线契约测试：临时 Git 仓库与模拟 Fetch，不访问真实管理接口或 LLM。
 * 测试重点是来源身份、固定提交、请求边界和有限重试，避免 202 被误当成发布成功。
 */
import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  describeReport, loadEdition, loadUpstreamEdition, makeBatches, prepareGeneration, publishBatches,
  requestJSON, sealGeneration, shanghaiDate,
} from "./publish.mjs";

const repository = "starcat-app/agents-radar";
const date = "2026-10-30";
const now = new Date("2026-10-30T01:00:00.000Z");
const markdown = "# AI CLI 日报\n\n这是实际生成的日报正文，包含真实的项目链接。\n\n[项目](https://github.com/example/repo)\n";

/** 独立 Git 仓库让测试能够证明未提交内容及后续无关提交不会污染发布身份。 */
function fixture(t) {
  const checkout = mkdtempSync(join(tmpdir(), "starcat-radar-pipeline-test-"));
  t.after(() => rmSync(checkout, { recursive: true, force: true }));
  const git = (...args) => execFileSync("git", ["-C", checkout, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  git("init", "-b", "master");
  git("config", "user.name", "Pipeline Test");
  git("config", "user.email", "test@example.invalid");
  git("config", "commit.gpgsign", "false");
  git("config", "core.hooksPath", "/dev/null");
  const write = (path, body) => {
    const full = join(checkout, path);
    mkdirSync(join(full, ".."), { recursive: true });
    writeFileSync(full, body);
  };
  const commit = () => {
    git("add", ".");
    git("commit", "-m", "test content");
    return git("rev-parse", "HEAD");
  };
  write(`digests/${date}/ai-cli.md`, "# Inherited upstream\n\nThis is upstream content, not generated by Starcat.");
  write("digests/2026-10-29/ai-cli.md", "# Earlier content\n\nMust not appear in the current day publication.");
  commit();
  return { checkout, git, write, commit };
}

function generated(t) {
  const f = fixture(t);
  prepareGeneration({ ...f, date, repository, sequence: 1001, now });
  f.write(`digests/${date}/ai-cli.md`, markdown);
  f.write(`digests/${date}/ai-cli-en.md`, "# AI CLI Digest\n\nA real daily report with more than fifteen characters.\n");
  f.write(`digests/${date}/highlights.json`, JSON.stringify({ zh: { "ai-cli": ["中文摘要一", "中文摘要二"] }, en: { "ai-cli": ["English highlight"] } }));
  f.write(`digests/${date}/index.md`, "# Old index\n\nThis remains upstream but is not a standard daily report.");
  sealGeneration({ ...f, date, repository, now });
  const commit = f.commit();
  return { ...f, sourceCommit: commit, options: { checkout: f.checkout, commit, date, repository } };
}

const envelope = (data, status = 200) => new Response(JSON.stringify({ schema_version: 1, data }), { status });
const batch = (status, total = 1, published = 0, failed = 0) => ({
  id: "batch-1", status, total, published, failed, items: [],
});

test("上海日期使用业务时区，非法日期/非当日不能生成", (t) => {
  assert.equal(shanghaiDate(new Date("2026-10-29T16:01:00Z")), date);
  const f = fixture(t);
  assert.throws(() => prepareGeneration({ ...f, date: "2026-02-30", repository, sequence: 1, now }), /YYYY-MM-DD/);
  assert.throws(() => prepareGeneration({ ...f, date: "2026-10-29", repository, sequence: 1, now }), /current Shanghai date/);
});

test("继承的上游文稿没有生成记录，不能发布为 Starcat 内容", (t) => {
  const f = fixture(t);
  assert.equal(loadEdition({ checkout: f.checkout, commit: f.git("rev-parse", "HEAD"), date, repository }), null);
  assert.throws(() => loadEdition({ checkout: f.checkout, commit: "HEAD", date, repository }), /40-character/);
});

test("固定生成提交、中英文、高亮与日期隔离；忽略未提交文件和无关后续提交", (t) => {
  const f = generated(t);
  const first = loadEdition(f.options);
  assert.equal(first.reports.length, 2);
  assert.equal(first.reports.find((r) => r.language === "zh-Hans").summary, "中文摘要一 · 中文摘要二");
  assert.equal(first.reports.find((r) => r.language === "en").summary, "English highlight");
  assert.deepEqual(first.skipped, [`digests/${date}/index.md`]);
  assert.equal(first.reports[0].source_commit, f.sourceCommit);
  assert.equal(first.reports[0].generated_at, "2026-10-30T01:00:00Z");
  assert.equal(first.reports[0].cover.card_url, null);
  assert.equal(first.reports[0].related_projects, undefined);
  f.write(`digests/${date}/ai-cli.md`, "# Uncommitted content\n\nMust not publish this text.");
  assert.deepEqual(loadEdition(f.options), first);
  f.write("unrelated.txt", "a subsequent commit");
  const laterCommit = f.commit();
  assert.deepEqual(loadEdition({ ...f.options, commit: laterCommit }), first);
  assert.deepEqual(makeBatches(loadEdition({ ...f.options, commit: laterCommit })), makeBatches(first));
});

test("来源仓库、文件摘要或空内容不匹配时拒绝发布", (t) => {
  const f = generated(t);
  assert.throws(() => loadEdition({ ...f.options, repository: "another/fork" }), /identity/);
  const markerPath = `digests/${date}/.starcat-generation.json`;
  const marker = JSON.parse(readFileSync(join(f.checkout, markerPath), "utf8"));
  marker.files["ai-cli.md"] = "invalid";
  f.write(markerPath, JSON.stringify(marker));
  const corruptCommit = f.commit();
  assert.throws(() => loadEdition({ ...f.options, commit: corruptCommit }), /generation record/);
  assert.throws(() => describeReport("# Title only\n", {}, "ai-cli", "en"), /body/);
  assert.throws(() => describeReport("# Failure\n\n⚠️ Summary generation failed.", {}, "ai-cli", "en"), /body/);
  assert.throws(() => describeReport("# Huge\n" + "x".repeat(1 << 20), {}, "ai-cli", "en"), /1 MiB/);
});

