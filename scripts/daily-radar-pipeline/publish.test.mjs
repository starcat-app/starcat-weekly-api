test("上游固定快照只读取标准报告，且同主题必须中英文成对", (t) => {
  const f = fixture(t);
  f.write(`digests/${date}/ai-cli.md`, markdown);
  f.write(`digests/${date}/ai-cli-en.md`, "# AI CLI Digest\n\nA real upstream report with more than fifteen characters.\n");
  f.write(`digests/${date}/index.md`, "# Upstream index\n\nNot a standard report.");
  const commit = f.commit();
  const edition = loadUpstreamEdition({ checkout: f.checkout, commit, date });
  assert.equal(edition.sourceKind, "upstream");
  assert.equal(edition.repository, "duanyytop/agents-radar");
  assert.equal(edition.commit, commit);
  assert.equal(edition.reports.length, 2);
  assert.ok(edition.reports.every((report) => report.source_commit === commit));
  assert.deepEqual(edition.skipped, [`digests/${date}/index.md`]);
  const batches = makeBatches(edition);
  assert.equal(batches[0].source_kind, "upstream");
  assert.equal(batches[0].source_repository, "duanyytop/agents-radar");

  f.write(`digests/${date}/ai-hn.md`, "# Only Chinese\n\nA single-language category cannot be published.");
  const broken = f.commit();
  assert.throws(
    () => loadUpstreamEdition({ checkout: f.checkout, commit: broken, date }),
    /ai-hn must provide both/,
  );
});

test("分批按 JSON 字节数与 50 项双重约束，重试保持幂等键", (t) => {
  const f = generated(t);
  const edition = loadEdition(f.options);
  const oneBytes = Buffer.byteLength(JSON.stringify(makeBatches({ ...edition, reports: [edition.reports[0]] })[0]));
  const split = makeBatches({ ...edition, reports: [edition.reports[0], edition.reports[0]] }, { maxBytes: oneBytes + 1 });
  assert.equal(split.length, 2);
  assert.equal(split[0].idempotency_key, split[1].idempotency_key);
  assert.equal(makeBatches({ ...edition, reports: Array(51).fill(edition.reports[0]) }).length, 2);
  const escaped = { ...edition.reports[0], markdown: "# Escaping\n\n" + "\"\\".repeat(400_000) };
  const fullSizeBatches = makeBatches({ ...edition, reports: Array(7).fill(escaped) });
  assert.ok(fullSizeBatches.length > 1);
  assert.ok(fullSizeBatches.every((request) => Buffer.byteLength(JSON.stringify(request)) <= 8 << 20));
  assert.throws(() => makeBatches(edition, { maxBytes: 100 }), /request limit/);
});

test("POST 网络失败、429 和 503 有限重试且请求内容完全一致", async () => {
  const sent = [];
  const delays = [];
  const fetchImpl = async (_url, options) => {
    sent.push(options);
    if (sent.length === 1) throw new Error("secret must not escape");
    if (sent.length === 2) return new Response("", { status: 429, headers: { "retry-after": "300" } });
    if (sent.length === 3) return new Response("", { status: 503 });
    return envelope(batch("processing"), 202);
  };
  await requestJSON("https://example.invalid/internal/daily-radar/imports", {
    token: "test-secret", method: "POST", body: { idempotency_key: "stable" }, fetchImpl,
    sleepImpl: async (ms) => { delays.push(ms); },
  });
  assert.equal(sent.length, 4);
  assert.ok(sent.every((item) => item.body === sent[0].body && item.redirect === "manual"));
  assert.equal(sent[0].headers["X-SC-Svc"], "weekly");
  assert.deepEqual(delays, [1000, 30_000, 4000]);
});

test("4xx 与重定向不重试；网络错误只返回脱敏结果", async () => {
  for (const status of [302, 400, 401, 403, 409]) {
    let calls = 0;
    await assert.rejects(() => requestJSON("https://example.invalid", {
      token: "sensitive", fetchImpl: async () => { calls += 1; return new Response("sensitive response", { status }); },
    }), new RegExp(`HTTP ${status}`));
    assert.equal(calls, 1);
  }
  let calls = 0;
  await assert.rejects(() => requestJSON("https://example.invalid", {
    token: "secret", maxAttempts: 3, sleepImpl: async () => {},
    fetchImpl: async () => { calls += 1; throw new Error("secret"); },
  }), /bounded retries/);
  assert.equal(calls, 3);
});

test("202 后轮询成功并核对数量，日志无凭据", async () => {
  const responses = [envelope(batch("processing"), 202), envelope(batch("processing")), envelope(batch("complete", 1, 1))];
  const logs = [];
  const requests = [];
  const result = await publishBatches([{ reports: [{}] }], {
    baseURL: "https://example.invalid", token: "sensitive-secret",
    fetchImpl: async (url, options) => { requests.push({ url, method: options.method }); return responses.shift(); },
    sleepImpl: async () => {}, log: (line) => logs.push(line),
  });
  assert.equal(result[0].published, 1);
  assert.deepEqual(requests.map((r) => r.method), ["POST", "GET", "GET"]);
  assert.ok(requests[1].url.endsWith("/internal/daily-radar/imports/batch-1"));
  assert.equal(logs.length, 2);
  assert.ok(!logs.join("\n").includes("sensitive-secret"));
});

test("partial、failed、完成数量错误和超时均不能报告成功", async () => {
  for (const result of [batch("partial", 2, 1, 1), batch("failed", 2, 0, 2), batch("complete", 2, 1)]) {
    await assert.rejects(() => publishBatches([{ reports: [{}, {}] }], {
      baseURL: "https://example.invalid", token: "key",
      fetchImpl: async () => envelope(result, 202), sleepImpl: async () => {}, log: () => {},
    }), /did not publish all reports/);
  }
  await assert.rejects(() => publishBatches([{ reports: [{}] }], {
    baseURL: "https://example.invalid", token: "key", pollTimeoutMs: 0,
    fetchImpl: async () => envelope(batch("processing"), 202), log: () => {},
  }), /still processing/);
  await assert.rejects(() => publishBatches([{ reports: [{}] }], {
    baseURL: "http://remote.example", token: "key",
  }), /HTTPS/);
});
